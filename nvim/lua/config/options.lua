-- OSC 52 clipboard — works over SSH, lets yank go to your local system clipboard
-- Requires a terminal that supports OSC 52 (iTerm2, Ghostty, Wezterm, Kitty, etc.)
vim.g.clipboard = {
  name = "OSC 52",
  copy = {
    ["+"] = require("vim.ui.clipboard.osc52").copy("+"),
    ["*"] = require("vim.ui.clipboard.osc52").copy("*"),
  },
  paste = {
    ["+"] = require("vim.ui.clipboard.osc52").paste("+"),
    ["*"] = require("vim.ui.clipboard.osc52").paste("*"),
  },
}
